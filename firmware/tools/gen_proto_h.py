#!/usr/bin/env python3
"""Generate include/aevea/proto_gen.h and tests/golden.h from docs/protocol.json.
Run:  python3 tools/gen_proto_h.py   (from firmware/).  Outputs are committed so the
C build needs no Python.  `make check-sync` regenerates into /tmp and diffs."""
import json, re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', '..', 'docs', 'protocol.json')
out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..')
d = json.load(open(src))

def ident(s):
    m = re.match(r'[A-Za-z0-9_]+', s)
    return m.group(0).upper()

o = []
w = o.append
w('/* GENERATED by tools/gen_proto_h.py from docs/protocol.json - DO NOT EDIT. */')
w('#ifndef AEVEA_PROTO_GEN_H\n#define AEVEA_PROTO_GEN_H\n')
w('#define AEV_PROTO_MAJOR %d\n#define AEV_PROTO_MINOR %d\n' % (d['version']['major'], d['version']['minor']))
for en, vals in d['enums'].items():
    w('/* enum %s */' % en)
    for k, v in vals.items():
        w('#define AEV_%s_%s %su' % (en.upper(), ident(v), k))
    w('')
w('/* error codes */')
for e in d['error_codes']:
    w('#define AEV_ERR_%s %su' % (e['name'], e['code']))
w('\n/* command opcodes, fixed request sizes (-1 = variable), response sizes (-1 = variable) */')
for c in d['commands']:
    rs = c.get('request_size'); ps = c.get('response_size')
    w('#define AEV_OP_%s %su' % (c['name'], c['opcode']))
    w('#define AEV_REQ_%s %s' % (c['name'], -1 if rs == 'var' else rs))
    w('#define AEV_RSP_%s %s' % (c['name'], -1 if ps == 'var' else ps))
w('\n/* event codes and payload sizes */')
for e in d['events']:
    w('#define AEV_EVT_%s %su' % (e['name'], e['code']))
    w('#define AEV_EVSZ_%s %d' % (e['name'], e['size']))
w('\n/* struct sizes */')
for k, s in d['structs'].items():
    w('#define AEV_SZ_%s %d' % (k.upper(), s['size']))
w('\n/* frame headers */')
for k, f in [(k, f) for k, f in d['frames'].items() if 'header_size' in f]:
    w('#define AEV_HDR_%s %d' % (k.upper(), f['header_size']))
w('\n/* bitfields */')
for bf, bits in d['bitfields'].items():
    for b, n in bits.items():
        w('#define AEV_%s_%s (1u << %s)' % (bf.upper(), n, b))
w('\n/* DFU */')
for op in d['dfu']['ops']:
    w('#define AEV_DFU_%s %su' % (op['name'].replace('DFU_', ''), op['op']))
dd = d['dfu']
w('#define AEV_DFU_OFFSET_CHECK_EVERY %d' % dd['offset_check_every_bytes'])
w('#define AEV_DFU_CONFIRM_DEADLINE_S %d' % dd['confirm_deadline_s'])
w('#define AEV_DFU_MAX_UNCONFIRMED_BOOTS %d' % dd['max_unconfirmed_boots'])
w('#define AEV_DFU_MIN_BATTERY_PCT %d' % dd['min_battery_pct'])
sm = d['state_machine']
w('\n/* state machine constants (assumption A9: starting values) */')
for k, v in sm['thresholds'].items():
    w('#define AEV_TH_%s %d' % (k.upper(), v))
for k, v in sm['timers_s'].items():
    w('#define AEV_TIMER_S_%s %d' % (k.upper(), v))
w('/* Lost Mode interval table: {battery_min_pct, interval_s}, highest first */')
w('#define AEV_LOST_INTERVAL_TABLE { %s }' % ', '.join('{%d, %d}' % (r['battery_min_pct'], r['interval_s']) for r in sm['lost_mode_interval_s']))
w('\n#endif')
open(os.path.join(out_dir, 'include/aevea/proto_gen.h'), 'w').write('\n'.join(o) + '\n')

# ---- golden vectors -------------------------------------------------------
g = ['/* GENERATED by tools/gen_proto_h.py from docs/protocol.json - DO NOT EDIT. */',
     '#ifndef AEVEA_GOLDEN_H\n#define AEVEA_GOLDEN_H',
     'typedef struct { const char *name; unsigned char opcode; const char *req; const char *rsp; } golden_cmd_t;',
     'static const golden_cmd_t GOLDEN_CMDS[] = {']
for c in d['commands']:
    ex = c.get('example', {})
    g.append('  { "%s", 0x%02X, "%s", "%s" },' % (c['name'], int(c['opcode'], 16), ex.get('request_hex', ''), ex.get('response_hex', '')))
g.append('};\n')
g.append('typedef struct { const char *name; unsigned char code; const char *hex; } golden_ev_t;')
g.append('static const golden_ev_t GOLDEN_EVS[] = {')
for e in d['events']:
    g.append('  { "%s", 0x%02X, "%s" },' % (e['name'], int(e['code'], 16), e.get('example_hex', '')))
g.append('};\n')
g.append('typedef struct { const char *name; const char *hex; } golden_struct_t;')
g.append('static const golden_struct_t GOLDEN_STRUCTS[] = {')
for k, s in d['structs'].items():
    g.append('  { "%s", "%s" },' % (k, s.get('example_hex', '')))
g.append('};')
g.append('typedef struct { const char *name; unsigned char op; const char *req; const char *ind; } golden_dfu_t;')
g.append('static const golden_dfu_t GOLDEN_DFU[] = {')
for op in dd['ops']:
    ex = op.get('example', {})
    g.append('  { "%s", 0x%02X, "%s", "%s" },' % (op['name'], int(op['op'], 16), ex.get('request_hex', ''), ex.get('indication_hex', '')))
g.append('};')
g.append('#define GOLDEN_ADV_HEX "%s"' % d['advertising']['manufacturer_data_example_hex'])
g.append('#endif')
open(os.path.join(out_dir, 'tests/golden.h'), 'w').write('\n'.join(g) + '\n')
print('generated')
